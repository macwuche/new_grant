export type DbConnection = {
  target: "supabase" | "replit";
  /** The URL as given (drizzle-kit needs this form for Replit's database). */
  url: string;
  host: string;
  port: number;
  user: string;
  password: string;
  database: string;
  ssl: PoolConfig["ssl"];
};

/** Connection settings for the app database; throws if neither URL is set. */
export function dbConnection(env: NodeJS.ProcessEnv = process.env): DbConnection {
  const supabase = env["SUPABASE_DATABASE_URL"];
  const raw = supabase || env["DATABASE_URL"];
  if (!raw) {
    throw new Error("SUPABASE_DATABASE_URL or DATABASE_URL must be set. Did you forget to provision a database?");
  }
  // Split into fields so a `sslmode` in the URL can't override the pinned CA.
  const url = new URL(raw);
  return {
    target: supabase ? "supabase" : "replit",
    url: raw,
    host: url.hostname,
    port: Number(url.port || 5432),
    user: decodeURIComponent(url.username),
    password: decodeURIComponent(url.password),
    database: decodeURIComponent(url.pathname.slice(1)) || "postgres",
    ssl: supabase ? { ca: SUPABASE_ROOT_CA } : undefined,
  };
}
